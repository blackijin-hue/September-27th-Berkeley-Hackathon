const STORAGE_KEY = 'last_mile_recall_vehicles_v8_oem_warranty';
const ACTIVE_VEHICLE_KEY = 'last_mile_active_vehicle_id_v8';

export function getStoredVehicles(): VehicleRecord[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.warn('Failed to parse stored vehicles:', e);
  }
  return INITIAL_VEHICLES;
}

export function saveStoredVehicles(vehicles: VehicleRecord[]): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(vehicles));
  } catch (e) {
    console.warn('Failed to persist vehicles:', e);
  }
}

export function resetStoredVehicles(): VehicleRecord[] {
  localStorage.removeItem(STORAGE_KEY);
  return INITIAL_VEHICLES;
}

export function getStoredActiveVehicleId(): string {
  try {
    const raw = localStorage.getItem(ACTIVE_VEHICLE_KEY);
    if (raw) return raw;
  } catch {}
  return 'VH-HMC-01'; // Min-Soo Park by default
}

export function saveStoredActiveVehicleId(id: string): void {
  try {
    localStorage.setItem(ACTIVE_VEHICLE_KEY, id);
  } catch {}
}
